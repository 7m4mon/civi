CONTROL_GROUPS = [('radio', ReceiverSettings), ('gains', Gains), ('meters', Meters),
                  ('scope', Scope), ('operations', RadioOperations)]


def command_mappings():
    mapped = {}

    def add(header, api, access):
        entry = mapped.setdefault(header, {'access': set(), 'apis': []})
        entry['access'].update(access)
        entry['apis'].append(api)

    for prefix, cls in CONTROL_GROUPS:
        for name, value in inspect.getmembers(cls):
            if isinstance(value, Setting):
                add(value.header, prefix + '.' + name, 'rw' if value.writable else 'r')
    for api, header, access in EXTRAS:
        add(header, api, access)
    for definition in definitions():
        add(definition.header, f'menus[{definition.number}].value', 'rw' if definition.writable else 'r')
    return mapped


def render():
    controls = [f'# Typed controls (client {__version__})', '',
                'Generated by `python tools/python_driver_docs.py`. No instrument I/O.', '',
                'Reference properties are read-only. Scalar writes validate before sending.',
                'Use `query_instrument_status=True` to raise queued device errors after scalar I/O.',
                'Readback reflects the radio; raw values can be rounded by hardware.',
                'Meters are uncalibrated; scope reference is a relative display offset, not dBm.', '']
    mapped = command_mappings()

    for prefix, cls in CONTROL_GROUPS:
        controls += ['## ' + prefix, '', '| Property | Type | Access | SCPI | Values |',
                     '|---|---|---|---|---|']
        for name, value in inspect.getmembers(cls):
            if not isinstance(value, Setting):
                continue
            access = 'rw' if value.writable else 'r'
            controls.append(f'| `{name}` | {type(value.default).__name__} | {access.upper()} | '
                            f'`{value.header}` | {value.__doc__} |')
        controls += ['']
    controls += ['## Explicit methods and compound values', '',
                 'See API.md for complete signatures, argument limits, units, exceptions and examples.', '',
                 '| API | SCPI | Access |', '|---|---|---|']
    for api, header, access in EXTRAS:
        controls.append(f'| `{api}` | `{header}` | {access.upper()} |')
    controls += ['', '`scope.start_stream()` uses STREAM then ENABLE; errors follow the status option.',
                 'With checks ON a failed second step attempts to restore the prior transfer setting.',
                 '`scope.stop_stream()` disables STREAM, preserving ENABLE.',
                 'Method groups are serialized within this driver, not across different network clients.', '']
    controls += ['All typed APIs follow the status option. Use `with device.checked():` for an explicit checked block.',
                 'With checks ON, STOP/OFF attempts still run with a prior error, then report prior/new errors.',
                 'See OPERATIONS.md for transmit/link/power gates and simulation limits.', '']

    menu_rows = [f'# Menu API catalog (client {__version__})', '',
                 'Generated by `python tools/python_driver_docs.py` from the packaged menu schema.',
                 'See API.md for record types, encoding, units and error behavior.', '',
                 'Use `menus[number].value` or the typed `boolean_item`/`integer_item`/record accessors.',
                 'All writes obey gateway permissions. Menu 0074 is read-only; 0028 is reserved.',
                 'Bounds refer to the listed unit, not automatically dB/Hz/percent.', '',
                 '| Number | Description | Type | Access | Range / step / unit | Choices | Permission |',
                 '|---|---|---|---|---|---|---|']
    for definition in definitions():
        access = 'rw' if definition.writable else 'r'
        record_bounds = {
            MenuKind.BOOLEAN: 'False / True',
            MenuKind.AUDIO_FILTER: 'HPF 0..20; LPF 5..25; bypass 0/25; HPF below LPF',
            MenuKind.BANDWIDTH: 'Two index codes 0..3',
            MenuKind.RGB: 'R/G/B each 0..255',
            MenuKind.SCOPE_EDGES: 'Ordered 0..74800000 Hz; whole 1000 Hz',
            MenuKind.DATE: '2000-01-01..2099-12-31; valid calendar date',
            MenuKind.TIME: '00:00..23:59; whole minutes',
        }
        bounds = (f'{definition.minimum}..{definition.maximum}; step {definition.step}; {definition.unit}'
                  if definition.minimum is not None else record_bounds.get(definition.kind, 'See API.md'))
        choices = ', '.join(str(x) for x in definition.choices) or '—'
        menu_rows.append(f'| {definition.number:04d} | {definition.description} | '
                         f'{definition.kind} | {access.upper()} | {bounds} | {choices} | {definition.permission} |')
    menu_rows += ['', 'Simulation defaults are protocol examples, not a claim of factory defaults.',
                  'Normal, link and calibration write permissions are independent and default OFF.', '']
    controls += ['## menus', '', 'See MENUS.md for all 216 definitions and API.md for typed values.', '']

    full = partial = missing = 0
    rows = []
    for header, spec in CATALOG.items():
        entry = mapped.get(header)
        access = entry['access'] if entry else set()
        if set(spec.access) <= access:
            status = 'Mapped'
            full += 1
        elif access:
            status = 'Partial'
            partial += 1
        else:
            status = 'Pending'
            missing += 1
        apis = ', '.join('`' + s + '`' for s in entry['apis']) if entry else '—'
        rows.append(f'| `{header}` | {spec.access.upper()} | {status} | {apis} |')
    coverage = [f'# Python driver command coverage ({__version__})', '',
                'Generated from the CIVI command catalog and the client API. This is a mapping inventory,',
                'not a hardware verification record or IVI conformance result.', '',
                f'{len(CATALOG)} extended definitions: **{full} mapped**, **{partial} partial**, '
                f'**{missing} pending**.', '',
                'Mapped means every catalog direction has a dedicated typed client API. Partial means',
                'at least one direction remains absent. Pending commands can still be sent through raw',
                'I/O in hardware mode, but raw I/O does not count as a dedicated typed implementation.',
                'SCPI_COVERAGE.md / PYTHON_SCPI_AUDIT.md add base commands, documented aliases and exclusions.',
                'Formal applicability and IVI requirements remain subject to the compliance audit.', '',
                'Core frequency/mode/S-meter, IDN/error/completion and CIVI receive reset are additional',
                'APIs outside this extended-command count. Simulation covers the documented client API;',
                'it is not a complete SCPI parser or RF/CI-V timing model.', '',
                '| Extended header | Gateway directions | Client status | API |', '|---|---|---|---|'] + rows + ['']
    return {
        ROOT / 'drivers/civi-ic7300/src/civi_ic7300/CONTROLS.md': '\n'.join(controls),
        ROOT / 'drivers/civi-ic7300/src/civi_ic7300/MENUS.md': '\n'.join(menu_rows),
        ROOT / 'docs/PYTHON_DRIVER_COVERAGE.md': '\n'.join(coverage),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in render().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding='utf-8')
            print(path.relative_to(ROOT))
    if stale:
        raise SystemExit('Regenerate driver docs: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
